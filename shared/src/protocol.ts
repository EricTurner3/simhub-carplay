/**
 * WebSocket protocol between a telemetry backend and the UI.
 *
 * This is the stable contract: the Phase 1 Node bridge and the Phase 2 SimHub
 * C# plugin must both speak it, so the UI never knows which one it talks to.
 *
 * Transport: JSON text frames on ws://<host>:<port>/ws.
 * Values are keyed by *channel* names (logical aliases defined in the game
 * profiles, games/*.json), never by raw SimHub property names.
 */

import type { ProfileInfo } from './games.ts';
import type { SettingsPatch, UiConfig } from './config.ts';

export const PROTOCOL_VERSION = 1;

export type ChannelValue = number | string | boolean | null;
export type ChannelMap = Record<string, ChannelValue>;

/** Navigation actions. Shared by local input (keyboard/gamepad) and backend-sent input. */
export const INPUT_ACTIONS = ['up', 'down', 'left', 'right', 'ok', 'back', 'toggleView', 'home'] as const;
export type InputAction = (typeof INPUT_ACTIONS)[number];

export function isInputAction(s: string): s is InputAction {
  return (INPUT_ACTIONS as readonly string[]).includes(s);
}

// ---- server -> client -------------------------------------------------------

/** First message on every connection. */
export interface HelloMsg {
  t: 'hello';
  v: typeof PROTOCOL_VERSION;
  /** Backend identifier, informational only ("mock", "propertyServer", "plugin"). */
  backend: string;
}

/** Full state. Sent right after hello, and whenever the backend wants to resync. */
export interface SnapshotMsg {
  t: 'snapshot';
  /** Backend clock, ms since epoch. */
  ts: number;
  d: ChannelMap;
}

/** Only channels that changed since the previous snapshot/delta. */
export interface DeltaMsg {
  t: 'delta';
  ts: number;
  d: ChannelMap;
}

/** Health of the backend's upstream (e.g. the TCP link to Property Server). */
export interface StatusMsg {
  t: 'status';
  upstream: 'connected' | 'connecting' | 'disconnected';
  detail?: string;
}

/**
 * The active game profile: sent on connect and whenever the game changes,
 * always followed by a fresh snapshot (the channel set may have changed).
 */
export interface ProfileMsg {
  t: 'profile';
  profile: ProfileInfo;
}

/**
 * A navigation action generated by the backend (e.g. a wheel button read by
 * SimHub). Lets the UI be driven even when the browser can't see the gamepad.
 */
export interface InputMsg {
  t: 'input';
  action: InputAction;
}

/** UI settings changed (by any screen's Settings app). Clients adopt the runtime-editable parts. */
export interface ConfigMsg {
  t: 'config';
  ui: UiConfig;
}

/**
 * Truck-game navigation route (ATS/ETS2), computed by the backend from the job
 * destination. Sent on connect and whenever the route changes; null = no route.
 * Progress along it arrives as ordinary channels (NAV_CHANNELS).
 */
export interface RouteMsg {
  t: 'route';
  route: NavRoute | null;
}

export type ServerMessage = HelloMsg | SnapshotMsg | DeltaMsg | StatusMsg | ProfileMsg | InputMsg | ConfigMsg | RouteMsg;

// ---- truck-game navigation ---------------------------------------------------

/**
 * Maneuver kinds. Values match truckermudgeon/maps' BranchType, so the backend
 * passes them through unchanged.
 */
export const Turn = {
  Through: 0,
  SlightLeft: 1,
  Left: 2,
  SharpLeft: 3,
  UTurnLeft: 4,
  SlightRight: 11,
  Right: 12,
  SharpRight: 13,
  UTurnRight: 14,
  /** Roundabout exits, by position: bottom-right, right, top-right, top, top-left, left, bottom-left, bottom. */
  RoundBR: 21,
  RoundR: 22,
  RoundTR: 23,
  RoundT: 24,
  RoundTL: 25,
  RoundL: 26,
  RoundBL: 27,
  RoundB: 28,
  RoundExit: 29,
  Merge: -1,
  Depart: -2,
  Arrive: -3,
  Ferry: -4,
} as const;
export type TurnKind = (typeof Turn)[keyof typeof Turn];

export interface NavStep {
  /** Maneuver at the start of this step. */
  turn: TurnKind;
  /** Where the maneuver happens. */
  lonLat: [number, number];
  /** Road name / exit / destination text, e.g. "I-84 W" or "Exit 27A". */
  text?: string;
  /** Sprite name of a road shield or POI icon (from the generated spritesheet). */
  icon?: string;
  roundaboutExit?: number;
  /** Lane guidance, left to right; `active` = lanes to use. */
  lanes?: { turns: TurnKind[]; active?: TurnKind }[];
  /** The maneuver right after this one, when it comes quickly. */
  then?: TurnKind;
  /** From this maneuver to the next one. */
  distanceM: number;
  durationS: number;
  /** Google encoded polyline (precision 5) from this maneuver to the next. */
  geometry: string;
}

export interface NavRoute {
  id: string;
  map: 'usa' | 'europe';
  steps: NavStep[];
  distanceM: number;
  durationS: number;
}

/**
 * Derived navigation channels the backend adds for truck games (alongside the
 * profile's own channels):
 *  - nav.stepIndex     index into NavRoute.steps of the NEXT maneuver (null: no route)
 *  - nav.maneuverDistM metres to that maneuver
 */
export const NAV_CHANNELS = ['nav.stepIndex', 'nav.maneuverDistM'] as const;

/** GET /maps/index.json: which games have generated map tiles. */
export interface MapIndex {
  games: ('ats' | 'ets2')[];
}

// ---- client -> server -------------------------------------------------------

/**
 * Operate a vehicle control from the active profile's `controls`.
 * tap = press + release (`count` taps in a row, max 5, for cycle controls);
 * press/release = hold, for momentary controls. Unknown ids are ignored, so a
 * client can only ever trigger what the profile allows.
 */
export interface ControlMsg {
  t: 'control';
  id: string;
  action: 'tap' | 'press' | 'release';
  count?: number;
}

/**
 * Change UI settings. The backend validates and saves them, then broadcasts a
 * ConfigMsg to every client (including the sender).
 */
export interface SettingsMsg {
  t: 'settings';
  patch: SettingsPatch;
}

export const MEDIA_ACTIONS = ['playPause', 'next', 'previous'] as const;
export type MediaAction = (typeof MEDIA_ACTIONS)[number];

/** Media transport button. Only does something when the backend reads media itself (media.source "windows"). */
export interface MediaMsg {
  t: 'media';
  action: MediaAction;
}

/** Reserved for future use. Backends may ignore. */
export interface CommandMsg {
  t: 'cmd';
  name: string;
  args?: Record<string, unknown>;
}

export type ClientMessage = ControlMsg | SettingsMsg | MediaMsg | CommandMsg;
