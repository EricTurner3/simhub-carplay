/**
 * WebSocket protocol between a telemetry backend and the UI.
 *
 * This is the stable contract: the Phase 1 Node bridge and the Phase 2 SimHub
 * C# plugin must both speak it, so the UI never knows which one it talks to.
 *
 * Transport: JSON text frames on ws://<host>:<port>/ws.
 * Values are keyed by *channel* names (logical aliases defined in the game
 * profiles, games/*.json), never by raw SimHub property names.
 */

import type { ProfileInfo } from './games.ts';

export const PROTOCOL_VERSION = 1;

export type ChannelValue = number | string | boolean | null;
export type ChannelMap = Record<string, ChannelValue>;

/** Navigation actions. Shared by local input (keyboard/gamepad) and backend-sent input. */
export const INPUT_ACTIONS = ['up', 'down', 'left', 'right', 'ok', 'back', 'toggleView', 'home'] as const;
export type InputAction = (typeof INPUT_ACTIONS)[number];

export function isInputAction(s: string): s is InputAction {
  return (INPUT_ACTIONS as readonly string[]).includes(s);
}

// ---- server -> client -------------------------------------------------------

/** First message on every connection. */
export interface HelloMsg {
  t: 'hello';
  v: typeof PROTOCOL_VERSION;
  /** Backend identifier, informational only ("mock", "propertyServer", "plugin"). */
  backend: string;
}

/** Full state. Sent right after hello, and whenever the backend wants to resync. */
export interface SnapshotMsg {
  t: 'snapshot';
  /** Backend clock, ms since epoch. */
  ts: number;
  d: ChannelMap;
}

/** Only channels that changed since the previous snapshot/delta. */
export interface DeltaMsg {
  t: 'delta';
  ts: number;
  d: ChannelMap;
}

/** Health of the backend's upstream (e.g. the TCP link to Property Server). */
export interface StatusMsg {
  t: 'status';
  upstream: 'connected' | 'connecting' | 'disconnected';
  detail?: string;
}

/**
 * The active game profile: sent on connect and whenever the game changes,
 * always followed by a fresh snapshot (the channel set may have changed).
 */
export interface ProfileMsg {
  t: 'profile';
  profile: ProfileInfo;
}

/**
 * A navigation action generated by the backend (e.g. a wheel button read by
 * SimHub). Lets the UI be driven even when the browser can't see the gamepad.
 */
export interface InputMsg {
  t: 'input';
  action: InputAction;
}

export type ServerMessage = HelloMsg | SnapshotMsg | DeltaMsg | StatusMsg | ProfileMsg | InputMsg;

// ---- client -> server -------------------------------------------------------

/** Reserved for future use (media controls, settings changes). Backends may ignore. */
export interface CommandMsg {
  t: 'cmd';
  name: string;
  args?: Record<string, unknown>;
}

export type ClientMessage = CommandMsg;
